"""The smartphone robot as a MuJoCo body, behind the robot env's interface.

Like `robot_sim.RobotSim` it subclasses the real env and replaces only the
link to the phone, so observations, actions, rewards, episodes and every
`env.robot.*` key are those of the robot. Selected by `env.robot.sim: True`
with `env.robot.sim_model: mujoco` (the default; `pendulum` is the older
planar model in robot_sim.py).

The body is the MuJoCo model of the SPR from tojo-soraai/smartphone-robot-
android, branch rl-sim2real (apps/rlSim2Real/mujoco, generated by
utils/generate_xml.py): chassis + phone 0.514 kg with its CoM 28 mm above the
axle and inertia (0.648, 0.759, 0.370) g m^2, wheels 35 g of radius 45 mm,
59.33 mm either side of the centre, rolling on contact cylinders. Only those
physical numbers are taken; the meshes are visual and left out. What is ours:

* Bumpers. One capsule under each end of the body's base plate, 64 mm in
  front of the axle and 86 mm behind it (the mesh's lowest edges), at the
  heights where the body rests on them at bumper_hi (front, +9.2 deg
  measured) and bumper_lo (back, -6.9) from theta_zero; their robot measured
  +8.5 / -6.4. The meshes, drawn for videos only, touch the floor there too.
* Signs. Positive tilt is a forward lean, toward +y, the way forward motor
  output (negative wheel speed) drives: on the robot (e1982 replay), forward
  output tips the body back, theta'' < 0, a tick after the wheels respond.
  Up to 2026-10-23 this model and robot_sim.py had it the other way round.
* The balance point theta_eq, drawn per run within +-sim_eq_range of
  theta_zero by shifting the CoM fore and aft, since the real one is unknown.
* The motors (fitted 2026-10-23 to tools/robot/dev/sysid_probe.py
  recordings, tools/robot/dev/sysid_fit.py). Their model drives the wheels
  with an ideal torque source, which their notes say overshoots the real top
  speed 2.8x. Here each wheel is a DC gear motor, torque = -stall * (u +
  omega / omega_max) for output u (positive output drives forward, which is
  negative wheel speed), against the gearbox's dry friction: sim_stick to
  start a still wheel, sim_slide once it turns, both as fractions of stall.
  The gearbox does not back-drive: with the motors at rest the encoders stay
  put while the body falls, so the wheels turn with the body and the robot
  rolls as one piece. The phone's own handling of an output comes first, as
  on the robot: within CURRENT_GAP of the output that holds the wheel's
  speed, and inside its dead zone +-MIN_DRIVE with the last output's sign
  (dreamerBridge main.py: limit_current, zero_fix).
* Units. Wheel speeds come out in the phone's mm/s, sim_speed_unit of them
  per rad/s of true wheel speed. The phone counts motor-side encoder ticks
  and assumes a 30 mm wheel; spinning in place, the gyro turned 1.65x faster
  than the wheels would at 905 phone mm/s per rad/s, on carpet and on the
  table alike and at every speed, so the unit is 548 and the wheels do not
  slip in a turn. Full output in the air is 5690 phone mm/s, ~10.4 rad/s.
* The floor (sim_surface). The wheels roll against MuJoCo's rolling friction
  and a contact of time constant sim_contact_tc, and the bumpers slide with
  sim_bumper_friction; 'carpet' and 'table' are fitted to each. On carpet the
  robot, its wheels held by the gearbox, can stay put leaning 3-5 deg, and a
  60 ms kick at 0.8 lifts it 6-9 deg off a bumper where on the table it goes
  over to the other one.
* Sides. The phone's _l wheel is the robot's right one, given that forward is
  negative wheel speed: speed_l > speed_r is a right turn, as the gyro shows
  (robot.py yaw_sign). Up to 2026-10-23 this model had them the other way.
* Timing: one tick between an observation and the action it prompts taking
  effect (the pipelined protocol), and the phone's sensor noise, as in
  robot_sim.py. The physics steps at ~2 ms, a whole number per tick.
"""

import math

import mujoco
import numpy as np

from embodied.envs import robot as robot_env
from embodied.envs import robot_sim

# What the phone does to an output before the base gets it (main.py).
DEAD_ZONE = 0.097
MIN_DRIVE = 0.13
CURRENT_GAP = 1.0
WHEEL_SPEED_MAX = 5700.0
# Joint names in the phone's order: its _l wheel is the robot's right.
PHONE_WHEELS = ('right', 'left')

# Fitted per floor (sysid_fit.py); any of them can be set as an env key.
# fit5/fit6 (2026-10-24): fit2's motor, each floor refitted on the probe's
# bumper tests plus real balancing (e2060 s01 carpet; e2061 s01, e2078 s01
# table) with rolling stiction free. Carpet (fit6, contact time constant
# capped at 0.03 s): a still wheel takes 4.5x the rolling resistance to
# start, so the carpet holds a 2-5 deg lean as the real one does (fit2's
# tipped over to a bumper). Table (fit5): its stiction, 6x a tiny rolling
# term, makes no difference; its soft contact (0.2 s) fits the table's
# balancing best but lets the body rest at +7.7 deg on the front bumper, not
# the measured +9.2 (capped at 0.03 s the table fits worse, 4.11 against
# 3.74). Held-out balancing (e2060 s02, e2061 s02) error against fit2:
# carpet 2.21 -> 2.00, table 3.90 -> 3.74.
SURFACES = {
    'carpet': dict(rolling=0.00432, contact_tc=0.0162, bumper_friction=0.357,
                   drag=3.99, rolling_static=0.0194, noslip=20),
    'table': dict(rolling=7e-5, contact_tc=0.197, bumper_friction=0.268,
                  drag=1.83, rolling_static=4.2e-4, noslip=20),
    # fit2 (2026-10-23, motor and both floors together, global search),
    # the floors of the runs up to e2341: rolling resistance on carpet ~140x
    # the table's, no stiction; `drag` alike on both.
    'carpet_fit2': dict(rolling=0.00505, contact_tc=0.041,
                        bumper_friction=0.572, drag=4.0),
    'table_fit2': dict(rolling=3.5e-5, contact_tc=0.148,
                       bumper_friction=0.345, drag=4.52),
    # Not fitted: carpet with 10x the rolling resistance, so that, like the
    # real carpet and unlike the fitted one, it holds the robot still where it
    # is left leaning 1-6 deg (sysid kicks: the real robot stops at 1-3 deg
    # after a kick; fit2's tips over to a bumper). For testing whether a
    # policy learnt on a floor that holds it up transfers to the table.
    'carpet_hold': dict(rolling=0.05, contact_tc=0.041, bumper_friction=0.572,
                        drag=4.0),
    # Not fitted either: the fitted carpet plus rolling stiction. A still
    # wheel takes 2.5x the fitted rolling resistance to start (holds a lean
    # up to ~6 deg, as the real carpet holds 3-5); a rolling one the fitted
    # value, so the robot drives as on carpet. carpet_hold, by contrast, is
    # so stiff that the motors cannot drive at all.
    'carpet_sticky': dict(rolling=0.00505, contact_tc=0.041,
                          bumper_friction=0.572, drag=4.0,
                          rolling_static=0.0125, noslip=20),
}

WHEEL_R = 0.045       # m
HALF_TRACK = 0.05933  # m, axle centre to wheel centre
CAPSULE_R = 0.005     # m, bumper capsule radius
FRONT_ARM = 0.0644    # m, front bumper ahead of the axle (+y)
BACK_ARM = 0.0857     # m, back bumper behind it (-y)


def _bumper_z(arm, angle):
  """Body-frame height of a bumper `arm` from the axle that rests at `angle`."""
  return (CAPSULE_R - WHEEL_R + arm * math.sin(angle)) / math.cos(angle)


# The rlSim2Real STL meshes (mm), for videos only: fetch them with
# tools/robot/dev/fetch_spr_meshes.sh. Poses as in its generate_xml.py,
# except that the body and phone sit MESH_DROP lower: placed as there, the
# body's lowest edges clear the floor by 11.4 mm at the tilts where the real
# robot rests on its bumpers (+9.2 / -6.9 deg). This drop makes both touch
# (it would take 11.65 mm at the front, 11.45 at the back). +y is the front.
MESH_DROP = 0.0115    # m
MESHES = {
    'spr_body': ('mesh_spr_body.stl', f'0 0 {-MESH_DROP}', '0 0 180'),
    'spr_phone': ('mesh_spr_phone.stl', f'-0.03965 0.02205 {-MESH_DROP}',
                  '180 0 0'),
    'spr_wheel_left': ('mesh_spr_wheel_left.stl', '0 0 0', '0 0 -90'),
    'spr_wheel_right': ('mesh_spr_wheel_right.stl', '0 0 0', '0 0 90'),
}


def model_xml(bumper_back, bumper_front, com_z=0.028, timestep=0.002,
              armature=5e-4, friction=1.0, rolling=0.0, contact_tc=0.02,
              bumper_friction=0.5, fixed=False, visual=None, meshdir=None):
  """MJCF of the robot. bumper_back > 0 and bumper_front > 0 are the pitch
  magnitudes (rad, from geometric upright) at which the body rests on the rear
  and front bumper. `visual` (an RGB phone colour) adds what a video needs --
  a checkered floor, a camera following from the side, push arrows -- and
  `meshdir` draws the robot with the rlSim2Real meshes (MESHES), hiding the
  physics shapes; without it a box stands in for the phone. None of this
  touches the physics: every visual geom is massless and collides with
  nothing. `rolling` is the wheels' rolling friction (m) and `contact_tc` the
  time constant of their contact with the floor (s); `fixed` holds the body
  in the air, wheels free, as on the stand the motors were measured on."""
  zb, zf = _bumper_z(BACK_ARM, bumper_back), _bumper_z(FRONT_ARM, bumper_front)
  meshes = visual is not None and meshdir is not None
  show = lambda rgba: 'rgba="0 0 0 0"' if meshes else f'rgba="{rgba}"'
  ghost = 'density="0" contype="0" conaffinity="0"'

  def mesh(name, rgba):
    if not meshes:
      return ''
    _, pos, euler = MESHES[name]
    return (f'<geom type="mesh" mesh="{name}" pos="{pos}" euler="{euler}" '
            f'rgba="{rgba}" {ghost}/>')

  head = body_extra = floor = ''
  if visual is not None:
    r, g, b = visual
    assets = ''.join(
        f'<mesh name="{name}" file="{meshdir}/{file}" scale=".001 .001 .001"/>'
        for name, (file, _, _) in MESHES.items()) if meshes else ''
    head = f"""
  <visual><global offwidth="1920" offheight="1080"/>
    <quality shadowsize="4096"/>
    <headlight ambient=".45 .45 .45" diffuse=".4 .4 .4" specular="0 0 0"/>
  </visual>
  <asset>{assets}
    <texture name="grid" type="2d" builtin="checker" width="512" height="512"
             rgb1=".95 .95 .93" rgb2=".84 .85 .83"/>
    <material name="floor" texture="grid" texrepeat="4 4" texuniform="true"/>
    <texture name="sky" type="skybox" builtin="gradient" rgb1="1 1 1"
             rgb2=".85 .88 .9" width="64" height="64"/>
  </asset>"""
    floor = 'material="floor"'
    # Arrows in the body frame: a backward push tips the top toward -y.
    arrow = lambda name, y0, y1: f"""
      <geom name="{name}" type="capsule" fromto="0 {y0} 0.16 0 {y1} 0.16"
            size="0.008" rgba=".84 .37 0 0" {ghost}/>
      <geom name="{name}_tip" type="sphere" pos="0 {y1} 0.16" size="0.016"
            rgba=".84 .37 0 0" {ghost}/>"""
    phone = mesh('spr_body', '.85 .85 .85 1') + mesh(
        'spr_phone', f'{r} {g} {b} 1') if meshes else f"""
      <geom type="box" size="0.037 0.005 0.075" pos="0 0.01 0.085"
            rgba="{r} {g} {b} 1" {ghost}/>
      <geom type="box" size="0.033 0.0005 0.068" pos="0 0.0157 0.085"
            rgba=".34 .71 .91 .9" {ghost}/>"""
    body_extra = f"""
      <light mode="trackcom" pos="-0.4 -0.4 1.2" dir="0.3 0.3 -1"
             diffuse=".6 .6 .6" specular=".1 .1 .1" castshadow="true"/>
      <camera name="follow" mode="trackcom" pos="0.42 -0.14 0.17"
              xyaxes="0.316 0.949 0 -0.229 0.076 0.970"/>
      {phone}
      {arrow('push_back', 0.20, 0.04)}
      {arrow('push_fwd', -0.20, -0.04)}"""

  wheel = lambda name, x: f"""
      <body name="{name}" pos="{x} 0 0">
        <joint name="{name}" type="hinge" axis="1 0 0" armature="{armature}"
               damping="1e-5" frictionloss="0.001"/>
        <geom type="cylinder" size="{WHEEL_R} 0.0084" euler="0 90 0"
              condim="6" friction="{friction} 0.005 {rolling}"
              solref="{contact_tc} 1" {show('.15 .15 .15 1')}/>
        {mesh('spr_wheel_' + name, '.15 .15 .15 1')}
        <inertial pos="0 0 0" mass="0.035" diaginertia="3.54e-05 1.85e-05 1.85e-05"/>
      </body>"""
  return f"""
<mujoco model="spr">
  <option timestep="{timestep}" integrator="implicitfast"/>{head}
  <worldbody>
    <!-- MuJoCo takes the larger of two geoms' frictions: the floor's is low
         so that the wheels' and bumpers' own are the ones that apply. -->
    <geom name="floor" type="plane" size="50 50 0.1" rgba=".8 .8 .8 1"
          friction="0.01 0 0" {floor}/>
    <body name="robot" pos="0 0 {0.3 if fixed else WHEEL_R}">
      {'' if fixed else '<freejoint name="robot"/>'}
      <inertial pos="0 0 {com_z}" mass="0.514"
                diaginertia="0.000648 0.000759 0.00037"/>
      <geom name="chassis" type="box" size="0.042 0.075 0.006" pos="0 0 -0.025"
            {show('.85 .85 .85 1')} {ghost}/>
      <geom name="bumper_back" type="capsule" size="{CAPSULE_R}"
            fromto="-0.03 {-BACK_ARM} {zb} 0.03 {-BACK_ARM} {zb}"
            density="0" friction="{bumper_friction} 0.005 0.0001" {show('.9 .3 .2 1')}/>
      <geom name="bumper_front" type="capsule" size="{CAPSULE_R}"
            fromto="-0.03 {FRONT_ARM} {zf} 0.03 {FRONT_ARM} {zf}"
            density="0" friction="{bumper_friction} 0.005 0.0001" {show('.9 .3 .2 1')}/>{body_extra}
      {wheel('left', -HALF_TRACK)}
      {wheel('right', HALF_TRACK)}
    </body>
  </worldbody>
  <!-- Torque gain * ctrl + bias * wheel speed: Physics sets the gain to the
       stall torque and the bias to its back-EMF, -stall / omega_max, which
       the implicitfast integrator then treats implicitly. -->
  <actuator>
    <general name="left" joint="left" gainprm="1" biastype="affine"
             biasprm="0 0 0"/>
    <general name="right" joint="right" gainprm="1" biastype="affine"
             biasprm="0 0 0"/>
  </actuator>
</mujoco>"""


def phone_output(u, speed, previous):
  """What the base gets for output `u` (dreamerBridge main.py drive):
  limit_current against the wheel's phone speed, then zero_fix against the
  previous requested output. Returns (sent, requested)."""
  held = -float(speed) / WHEEL_SPEED_MAX
  u = max(held - CURRENT_GAP, min(held + CURRENT_GAP, float(u)))
  if abs(u) >= DEAD_ZONE:
    return u, u
  return (MIN_DRIVE if previous >= 0 else -MIN_DRIVE), u


class Physics:
  """The body, its two gear motors and the floor, stepped at the output the
  base was sent. Wheel quantities are in the phone's order (_l first)."""

  STILL = 0.05  # rad/s: a wheel slower than this takes the sticking friction
  ROLL_STILL = 0.3  # rad/s: a wheel rolling slower is held by rolling_static

  def __init__(self, bumper_back, bumper_front, timestep, wheel_omega=11.61,
               stall=0.0884, stick=0.385, slide=0.098, armature=4.16e-4,
               unit=548.0, friction=1.0, rolling=0.0, contact_tc=0.02,
               bumper_friction=0.5, drag=0.0, rolling_static=None,
               noslip=0, fixed=False):
    self.omega_max = float(wheel_omega)
    self.stall = float(stall)
    self.stick = float(stick) * self.stall   # N m
    self.slide = float(slide) * self.stall
    self.unit = float(unit)
    self.drag = 0.0 if fixed else float(drag)   # N per m/s, both wheels
    self.model = mujoco.MjModel.from_xml_string(model_xml(
        bumper_back, bumper_front, timestep=timestep, armature=armature,
        friction=friction, rolling=rolling, contact_tc=contact_tc,
        bumper_friction=bumper_friction, fixed=fixed))
    self.data = mujoco.MjData(self.model)
    joints = [self.model.joint(n).id for n in PHONE_WHEELS]
    self.dofs = [int(self.model.jnt_dofadr[j]) for j in joints]
    self.acts = [self.model.actuator(n).id for n in PHONE_WHEELS]
    for act in self.acts:
      self.model.actuator_gainprm[act, 0] = self.stall
      self.model.actuator_biasprm[act, 2] = -self.stall / self.omega_max
    self.bodies = [self.model.body(n).id for n in PHONE_WHEELS]
    self._vel = np.zeros(6)
    # Each wheel's contact geom, in the same (phone) order as dofs.
    self.wheel_geoms = [
        next(g for g in range(self.model.ngeom)
             if self.model.geom_bodyid[g] == body
             and self.model.geom_contype[g])
        for body in self.bodies]
    self._set_rolling(rolling, rolling_static, noslip)

  def _set_rolling(self, rolling, rolling_static, noslip):
    # Rolling stiction (sim_surface carpet_sticky): a wheel standing still in
    # the pile takes rolling_static to start, one that rolls takes `rolling`.
    # With noslip iterations the static part holds instead of creeping, as
    # MuJoCo's soft contacts otherwise let it.
    self.rolling = float(rolling)
    self.rolling_static = (self.rolling if rolling_static is None
                           else float(rolling_static))
    self.model.opt.noslip_iterations = int(noslip)

  @property
  def speed(self):
    """Wheel speeds in the phone's mm/s and sign (forward is negative)."""
    return np.array([self.data.qvel[i] for i in self.dofs]) * self.unit

  def set_floor(self, rolling, contact_tc, bumper_friction, drag,
                rolling_static=None, noslip=0):
    """Change the floor in place: what model_xml sets per surface."""
    m = self.model
    self._set_rolling(rolling, rolling_static, noslip)
    for body in self.bodies:
      for g in range(m.ngeom):
        if m.geom_bodyid[g] == body and m.geom_contype[g]:
          m.geom_friction[g, 2] = rolling
          m.geom_solref[g, 0] = contact_tc
    for name in ('bumper_back', 'bumper_front'):
      m.geom_friction[m.geom(name).id, 0] = bumper_friction
    self.drag = float(drag)
    self.data.qfrc_applied[:] = 0.0  # the old floor's drag, if any

  def step(self, sent, n):
    """`n` physics steps with outputs `sent` (phone order) at the motors."""
    m, d = self.model, self.data
    for _ in range(n):
      for u, dof, act in zip(sent, self.dofs, self.acts):
        w = float(d.qvel[dof])
        d.ctrl[act] = -u
        m.dof_frictionloss[dof] = (
            self.stick if abs(w) < self.STILL else self.slide)
      if self.drag:
        self._floor_drag()
      if self.rolling_static != self.rolling:
        for dof, geom in zip(self.dofs, self.wheel_geoms):
          # The wheel's spin relative to the floor: its joint's plus the
          # body's pitch rate (the free joint's, in the body frame).
          spin = abs(float(d.qvel[dof]) + float(d.qvel[3]))
          m.geom_friction[geom, 2] = (
              self.rolling_static if spin < self.ROLL_STILL else self.rolling)
      mujoco.mj_step(m, d)

  def _floor_drag(self):
    """A floor that drags on a rolling wheel in proportion to its speed, at
    the point where it touches: carpet. Applied there, it pitches the body
    the way a wheel stopping on the floor does."""
    m, d = self.model, self.data
    d.qfrc_applied[:] = 0.0
    for body in self.bodies:
      mujoco.mj_objectVelocity(m, d, mujoco.mjtObj.mjOBJ_BODY, body,
                               self._vel, 0)
      force = -0.5 * self.drag * np.array([self._vel[3], self._vel[4], 0.0])
      point = d.xpos[body] - np.array([0.0, 0.0, WHEEL_R])
      mujoco.mj_applyFT(m, d, force, np.zeros(3), point, body,
                        d.qfrc_applied)


class RobotMujoco(robot_sim.RobotSim):

  def __init__(
      self, task, sim_hz=None, sim_wheel_omega=11.61, sim_stall_torque=0.0884,
      sim_stick=0.385, sim_slide=0.098, sim_armature=4.16e-4,
      sim_speed_unit=548.0, sim_surface='carpet', sim_rolling=None,
      sim_contact_tc=None, sim_bumper_friction=None, sim_drag=None,
      sim_schedule='', sim_carry_s=0.0, sim_noise=1.0,
      sim_eq_range=0.0175, sim_substep=0.002, sim_friction=1.0, seed=0,
      **kwargs):
    for key in ('host', 'port', 'reconnect', 'onboard', 'weights_every',
                'pace', 'config', 'policy_dir', 'sim_air_speed'):
      kwargs.pop(key, None)
    # Keys of the planar model; not used here.
    for key in ('sim_w0', 'sim_length', 'sim_damping', 'sim_motor_tau',
                'sim_track'):
      kwargs.pop(key, None)
    if sim_hz:
      kwargs['hz'] = sim_hz
    robot_env.SmartphoneRobot.__init__(
        self, task, seed=seed, onboard=False, reconnect=False, **kwargs)
    self._overrides = {}
    for key, value in (('rolling', sim_rolling), ('contact_tc', sim_contact_tc),
                       ('bumper_friction', sim_bumper_friction),
                       ('drag', sim_drag)):
      if value is not None:
        self._overrides[key] = float(value)
    # sim_schedule: move the robot to another floor while it trains, as a
    # person does with the real one: 'carpet:10,table:20,carpet' is 10 min
    # on carpet, 20 on the table, then carpet for good (minutes of sim time).
    # At each move the robot is picked up and set down on a bumper.
    self._schedule = []
    at = 0.0
    for part in [p for p in str(sim_schedule).split(',') if p.strip()]:
      name, _, minutes = part.strip().partition(':')
      assert name in SURFACES, name
      self._schedule.append((at, name))
      at += float(minutes) * 60 if minutes else np.inf
    if self._schedule:
      sim_surface = self._schedule[0][1]
    self.surface = sim_surface
    self._sim_time = 0.0
    # sim_carry_s: a move takes this long in someone's hands -- lifted, the
    # wheels in the air under the policy's outputs, the body swinging through
    # +-15 deg -- before it is set down on the new floor. Training goes on
    # through it, as it does on the robot.
    self.carry_s = float(sim_carry_s)
    self._carry = None   # (seconds left, destination, phase)
    floor = dict(SURFACES[sim_surface], **self._overrides)
    self.track = 2 * HALF_TRACK
    self.noise = float(sim_noise)
    self.substeps = max(1, int(round(1.0 / self.hz / float(sim_substep))))
    self.sim_rng = np.random.RandomState(seed + 7919)
    self.physics = Physics(
        -self.bumper_lo, self.bumper_hi, 1.0 / self.hz / self.substeps,
        wheel_omega=sim_wheel_omega, stall=sim_stall_torque, stick=sim_stick,
        slide=sim_slide, armature=float(sim_armature), unit=sim_speed_unit,
        friction=float(sim_friction), **floor)
    self.model, self.data = self.physics.model, self.physics.data
    self._body = self.model.body('robot').id
    self._com = self.model.body_ipos[self._body].copy()
    # Upright in MuJoCo is theta_zero here: the phone reads tilt from its own
    # mount, and theta_zero is where that reading was set to zero by eye.
    self.theta_eq = self.theta_zero + self.sim_rng.uniform(
        -sim_eq_range, sim_eq_range)
    # Start leaning on a bumper, as a robot that was just set down does.
    self.theta = self.theta_zero + (
        self.bumper_hi if self.sim_rng.rand() < 0.5 else self.bumper_lo)
    self.distance = np.zeros(2)    # phone mm
    self.applied = np.zeros(2)
    self.requested = np.zeros(2)   # the phone's last_command
    self.kicked = [False, False]
    self.previous = np.zeros(2)
    self.pending = np.zeros(2)
    self.cmd_target = (0.0, 0.0)
    self.cmd_now = np.zeros(2)
    self.cmd_left = 0.0

  # Body state in the robot env's terms, readable and settable like the
  # planar model's attributes (tools/robot/dev/sim_rollout.py does both).

  @property
  def theta_eq(self):
    return self._theta_eq

  @theta_eq.setter
  def theta_eq(self, value):
    self._theta_eq = float(value)
    # CoM straight above the axle at tilt theta_eq - theta_zero, i.e. a
    # rotation about x by minus that (forward, toward +y, is positive).
    lean = self._theta_eq - self.theta_zero
    self.model.body_ipos[self._body] = (
        0.0, -self._com[2] * math.tan(lean), self._com[2])
    mujoco.mj_setConst(self.model, self.data)

  # Tilt is minus the rotation about the body's x axis: a forward lean takes
  # the top toward +y.
  @property
  def theta(self):
    w, x, y, z = self.data.qpos[3:7]
    return self.theta_zero - math.atan2(2 * (w * x + y * z),
                                        1 - 2 * (x * x + y * y))

  @theta.setter
  def theta(self, value):
    yaw = self._yaw()
    pitch = self.theta_zero - float(value)
    cy, sy = math.cos(yaw / 2), math.sin(yaw / 2)
    cp, sp = math.cos(pitch / 2), math.sin(pitch / 2)
    self.data.qpos[3:7] = (cy * cp, cy * sp, sy * sp, sy * cp)
    self.data.qpos[2] = WHEEL_R
    mujoco.mj_forward(self.model, self.data)

  @property
  def omega(self):
    return -float(self.data.qvel[3])

  @omega.setter
  def omega(self, value):
    self.data.qvel[3] = -float(value)

  @property
  def speed(self):
    """Wheel speeds in the phone's mm/s and sign (forward is negative)."""
    return self.physics.speed

  def _hold(self, dt):
    """Carried: the body 12 cm up, swinging slowly; the wheels spin free."""
    left, _, phase = self._carry
    t = self.carry_s - left
    swing = math.radians(15.0)
    theta = self.theta_zero + swing * math.sin(2 * math.pi * 0.3 * t + phase)
    rate = swing * 2 * math.pi * 0.3 * math.cos(2 * math.pi * 0.3 * t + phase)
    self.theta = theta
    self.data.qpos[2] = 0.12
    self.data.qvel[0:3] = 0.0
    self.data.qvel[3] = -rate
    self.data.qvel[4:6] = 0.0
    mujoco.mj_forward(self.model, self.data)

  def move_to(self, surface):
    """Pick the robot up and set it down on another floor, on a bumper."""
    if hasattr(self, '_drag_saved'):
      del self._drag_saved
    self.physics.set_floor(**dict(SURFACES[surface], **self._overrides))
    print(f'[robot sim] {self._sim_time / 60:.1f} min: moved from '
          f'{self.surface} to {surface}', flush=True)
    self.surface = surface
    self.data.qvel[:] = 0.0
    self.theta = self.theta_zero + (
        self.bumper_hi if self.sim_rng.rand() < 0.5 else self.bumper_lo)

  def _compensate(self, a, speed, wheel):
    """The phone's friction_comp (main.py compensate), when the run asks."""
    if abs(a) < 0.02:
      self.kicked[wheel] = False
      return 0.0
    out = math.copysign(0.12 + 0.88 * abs(a), a)
    if abs(speed) < 100.0 and not self.kicked[wheel] and abs(out) < 0.32:
      self.kicked[wheel] = True
      return math.copysign(0.32, a)
    self.kicked[wheel] = False
    return out

  def _yaw(self):
    w, x, y, z = self.data.qpos[3:7]
    return math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))

  def _recv(self):
    dt = 1.0 / self.hz
    self.applied, self.previous = self.previous, self.pending
    speed = self.speed
    sent = []
    for i, u in enumerate(np.clip(self.applied, -1.0, 1.0)):
      if self.friction_comp:
        u = self._compensate(u, speed[i], i)
      out, self.requested[i] = phone_output(u, speed[i], self.requested[i])
      sent.append(out)
    if self._carry:
      self._hold(dt)
    self.physics.step(sent, self.substeps)
    if self._carry:
      self._hold(dt)
    self._sample_command(dt)
    self._sim_time += dt
    if self._carry:
      left, dest, phase = self._carry
      self._carry = (left - dt, dest, phase) if left > dt else None
      if not self._carry:
        self.move_to(dest)
    elif self._schedule:
      due = [name for at, name in self._schedule if at <= self._sim_time][-1]
      if due != self.surface:
        if self.carry_s:
          print(f'[robot sim] {self._sim_time / 60:.1f} min: picked up',
                flush=True)
          self._carry = (self.carry_s, due, self.sim_rng.uniform(0, 6.28))
          self._drag_saved = self.physics.drag
          self.physics.drag = 0.0
          self.data.qfrc_applied[:] = 0.0
        else:
          self.move_to(due)
    speed = self.speed
    self.distance += speed * dt
    n = self.noise
    rng = self.sim_rng
    noisy = speed * (1 + 0.02 * n * rng.randn(2)) + 30 * n * rng.randn(2)
    # Yaw rate about the vertical, counter-clockwise positive, signed as the
    # phone's gyro is after yaw_sign.
    self._yaw_rate = self.yaw_sign * (
        float(self.data.qvel[5]) + 0.02 * n * rng.randn())
    self._last = dict(
        wheel_speed_l=float(noisy[0]), wheel_speed_r=float(noisy[1]),
        wheel_distance_l=float(self.distance[0]),
        wheel_distance_r=float(self.distance[1]),
        theta=float(self.theta + 0.003 * n * rng.randn()),
        angular_velocity=float(self.omega + 0.05 * n * rng.randn()),
        battery_voltage=3.6)
    self._timing = (0.0, 0.0, 0.0, 0.0)
    self._backlog = 0
    self._dropped = 0
    return self._last, dt
